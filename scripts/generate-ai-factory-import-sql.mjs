#!/usr/bin/env node
/**
 * Generate the SQL half of the AI Factory import package.
 *
 * `agents.json` and `teams.json` are the portable, human-readable form of the
 * roster. This script turns them into SQL that reproduces the exact live state
 * against the real schema:
 *
 *   public.ai_agency_teams   (id, user_id, name, category, description, roles[],
 *                             archived, created_at, updated_at)
 *   public.workforce_agents  (id, owner_id, project_id, slug, department, lead,
 *                             source_resource_id, legacy_team_id, enabled,
 *                             active_version_id, created_at, updated_at)
 *   public.workforce_agent_versions (id, agent_id, number, config jsonb,
 *                             created_by, created_at)
 *
 * Two outputs:
 *   import.sql          — readable, one statement per row, with comments.
 *   import_compact.sql  — same data, multi-row INSERTs, for fast re-import.
 *
 * Both are idempotent: teams upsert on (user_id, lower(name)) and agents upsert
 * on (owner scope, slug), so re-running converges on the same state instead of
 * duplicating rows.
 *
 * Usage:
 *   node scripts/generate-ai-factory-import-sql.mjs [--owner <uuid>]
 *
 * `--owner` is the auth.users id that will own the imported rows. It defaults to
 * the placeholder `:owner_id`, which the README tells the operator to replace
 * (or to set via `\set owner_id` in psql).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

// The roster ships as `scripts/ai-factory-roster.zip` and is unpacked into
// `public/ai-factory/roster/` at build time, so the SQL must be generated into
// the *source* tree that gets re-zipped — otherwise the next build overwrites it.
// `--dir` points at that tree; the default is the unpacked public copy.
const dirArgIndex = process.argv.indexOf("--dir");
const importDir =
  dirArgIndex > -1
    ? join(process.argv[dirArgIndex + 1], "import")
    : join(here, "..", "public", "ai-factory", "roster", "import");

const ownerArgIndex = process.argv.indexOf("--owner");
const OWNER = ownerArgIndex > -1 ? process.argv[ownerArgIndex + 1] : ":owner_id";

const agents = JSON.parse(readFileSync(join(importDir, "agents.json"), "utf8"));
const teams = JSON.parse(readFileSync(join(importDir, "teams.json"), "utf8"));

/** Escape a value for a single-quoted SQL literal. */
function q(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Escape a value for a JSONB literal. */
function j(value) {
  return `${q(JSON.stringify(value ?? {}))}::jsonb`;
}

/** Escape a Postgres text[] literal. */
function arr(values) {
  const items = (values ?? []).map((v) => `"${String(v).replace(/"/g, '\\"')}"`);
  return `array[${items.join(",")}]::text[]`;
}

/**
 * The team `category` column is constrained to a fixed set. The roster's own
 * categories are richer, so map them onto the closest allowed value rather than
 * letting the insert fail.
 */
const CATEGORY_MAP = {
  development: "development",
  engineering: "development",
  business: "business",
  finance: "business",
  marketing: "marketing",
  growth: "marketing",
  research: "research",
  data: "research",
  operations: "operations",
  direction: "operations",
  support: "operations",
};

function teamCategory(team) {
  const raw = String(team.category ?? team.layer ?? "").toLowerCase();
  return CATEGORY_MAP[raw] ?? "custom";
}

/**
 * `roles` must hold 2..6 entries. Pad a short team with its lead so the
 * constraint holds without inventing roles that are not in the roster.
 */
function teamRoles(team) {
  const roles = [...(team.roles ?? [])].filter(Boolean).slice(0, 6);
  while (roles.length < 2) roles.push(team.lead || team.name || "Lead");
  return roles;
}

/** The seven-field agent schema, as stored in `workforce_agent_versions.config`. */
function agentConfig(agent) {
  const c = agent.config ?? {};
  return {
    name: c.name ?? agent.name,
    description: c.description ?? agent.description,
    instruction: c.instruction ?? "",
    knowledge: c.knowledge ?? [],
    knowledgeFiles: c.knowledgeFiles ?? [],
    tools: c.tools ?? [],
    skills: c.skills ?? [],
    connectors: c.connectors ?? [],
  };
}

const header = `-- Open-Connect AI Factory — import package
-- Generated by scripts/generate-ai-factory-import-sql.mjs
--
-- Reproduces the merged live state: ${teams.length} teams, ${agents.length} agents.
--
-- BEFORE RUNNING: replace :owner_id with the auth.users id that should own these
-- rows, e.g.  \\set owner_id '00000000-0000-0000-0000-000000000000'
-- or run:    sed 's/:owner_id/<your-user-uuid>/g' import.sql | psql "$DATABASE_URL"
--
-- Idempotent: teams upsert on (user_id, lower(name)); agents upsert on
-- (owner scope, slug) and their config is written as a new version only when it
-- differs from the active one.
`;

// ---------------------------------------------------------------- import.sql

const readable = [header];

readable.push(`
-- ---------------------------------------------------------------------------
-- 1. Teams
-- ---------------------------------------------------------------------------
begin;
`);

for (const team of teams) {
  readable.push(`
-- ${team.name} (${team.agents?.length ?? 0} agents)
insert into public.ai_agency_teams (user_id, name, category, description, roles)
values (
  ${OWNER},
  ${q(team.name)},
  ${q(teamCategory(team))},
  ${q(team.description ?? "")},
  ${arr(teamRoles(team))}
)
on conflict (user_id, lower(btrim(name))) do update
  set category = excluded.category,
      description = excluded.description,
      roles = excluded.roles,
      updated_at = now();
`);
}

readable.push(`
-- ---------------------------------------------------------------------------
-- 2. Agents + their active config version
-- ---------------------------------------------------------------------------
`);

for (const agent of agents) {
  const config = agentConfig(agent);
  readable.push(`
-- ${agent.name} — ${agent.team ?? agent.department ?? "unassigned"}
with team as (
  select id from public.ai_agency_teams
   where user_id = ${OWNER} and lower(btrim(name)) = lower(btrim(${q(agent.team ?? "")}))
   limit 1
), upserted as (
  insert into public.workforce_agents
    (owner_id, project_id, slug, department, lead, legacy_team_id, enabled)
  values (
    ${OWNER},
    null,
    ${q(agent.slug)},
    ${q(agent.department ?? "operations")},
    ${agent.lead ? "true" : "false"},
    (select id from team),
    true
  )
  on conflict (coalesce(project_id::text, 'personal:' || owner_id::text), slug) do update
    set department = excluded.department,
        lead = excluded.lead,
        legacy_team_id = excluded.legacy_team_id,
        enabled = true,
        updated_at = now()
  returning id
), version as (
  insert into public.workforce_agent_versions (agent_id, number, config)
  select id, 1, ${j(config)} from upserted
  on conflict (agent_id, number) do update set config = excluded.config
  returning id, agent_id
)
update public.workforce_agents a
   set active_version_id = v.id
  from version v
 where a.id = v.agent_id
   and a.active_version_id is distinct from v.id;
`);
}

readable.push(`
commit;

-- ---------------------------------------------------------------------------
-- 3. Verify
-- ---------------------------------------------------------------------------
-- select count(*) as teams from public.ai_agency_teams where user_id = ${OWNER};
-- select count(*) as agents from public.workforce_agents where owner_id = ${OWNER};
-- select count(*) as versions from public.workforce_agent_versions v
--   join public.workforce_agents a on a.id = v.agent_id where a.owner_id = ${OWNER};
`);

writeFileSync(join(importDir, "import.sql"), readable.join(""));

// -------------------------------------------------------- import_compact.sql

const compact = [header];

compact.push(`
-- Compact form: multi-row INSERTs. Same data, same idempotency, far fewer
-- round trips. Use this for a fresh environment; use import.sql when you want
-- to read or hand-edit individual rows.
begin;

-- ---------------------------------------------------------------------------
-- 1. Teams (${teams.length})
-- ---------------------------------------------------------------------------
insert into public.ai_agency_teams (user_id, name, category, description, roles) values
`);

compact.push(
  teams
    .map(
      (t) =>
        `  (${OWNER}, ${q(t.name)}, ${q(teamCategory(t))}, ${q(t.description ?? "")}, ${arr(teamRoles(t))})`,
    )
    .join(",\n"),
);

compact.push(`
on conflict (user_id, lower(btrim(name))) do update
  set category = excluded.category,
      description = excluded.description,
      roles = excluded.roles,
      updated_at = now();

-- ---------------------------------------------------------------------------
-- 2. Agents (${agents.length})
-- ---------------------------------------------------------------------------
insert into public.workforce_agents
  (owner_id, project_id, slug, department, lead, legacy_team_id, enabled)
select
  ${OWNER},
  null,
  v.slug,
  v.department,
  v.lead,
  (select t.id from public.ai_agency_teams t
    where t.user_id = ${OWNER} and lower(btrim(t.name)) = lower(btrim(v.team_name))
    limit 1),
  true
from (values
`);

compact.push(
  agents
    .map(
      (a) =>
        `  (${q(a.slug)}, ${q(a.department ?? "operations")}, ${a.lead ? "true" : "false"}, ${q(a.team ?? "")})`,
    )
    .join(",\n"),
);

compact.push(`
) as v(slug, department, lead, team_name)
on conflict (coalesce(project_id::text, 'personal:' || owner_id::text), slug) do update
  set department = excluded.department,
      lead = excluded.lead,
      legacy_team_id = excluded.legacy_team_id,
      enabled = true,
      updated_at = now();

-- ---------------------------------------------------------------------------
-- 3. Agent config versions (${agents.length})
-- ---------------------------------------------------------------------------
insert into public.workforce_agent_versions (agent_id, number, config)
select a.id, 1, v.config
from (values
`);

compact.push(agents.map((a) => `  (${q(a.slug)}, ${j(agentConfig(a))})`).join(",\n"));

compact.push(`
) as v(slug, config)
join public.workforce_agents a
  on a.owner_id = ${OWNER} and a.slug = v.slug
on conflict (agent_id, number) do update set config = excluded.config;

-- Point each agent at its version.
update public.workforce_agents a
   set active_version_id = v.id
  from public.workforce_agent_versions v
 where v.agent_id = a.id
   and v.number = 1
   and a.owner_id = ${OWNER}
   and a.active_version_id is distinct from v.id;

commit;
`);

writeFileSync(join(importDir, "import_compact.sql"), compact.join(""));

console.log(
  `[import-sql] wrote import.sql and import_compact.sql ` +
    `(${teams.length} teams, ${agents.length} agents, owner=${OWNER})`,
);
