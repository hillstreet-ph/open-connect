const encoder = new TextEncoder();
function crc(bytes: Uint8Array) {
  let value = 0xffffffff;
  for (const byte of bytes) {
    value ^= byte;
    for (let bit = 0; bit < 8; bit++) value = (value >>> 1) ^ (value & 1 ? 0xedb88320 : 0);
  }
  return (value ^ 0xffffffff) >>> 0;
}
/** Small deterministic STORE ZIP. Fixed generated paths only; no uploaded archives are executed. */
export function setupZip(files: Record<string, string>): Uint8Array {
  const chunks: Uint8Array[] = [],
    directory: Uint8Array[] = [];
  let offset = 0;
  const header = (size: number) => new DataView(new ArrayBuffer(size));
  for (const [path, content] of Object.entries(files)) {
    if (!path || path.startsWith("/") || path.split("/").includes("..") || /[\\\0:]/.test(path))
      throw new Error("Unsafe setup path");
    const name = encoder.encode(path),
      body = encoder.encode(content),
      sum = crc(body),
      local = header(30),
      central = header(46);
    local.setUint32(0, 0x04034b50, true);
    local.setUint16(4, 20, true);
    local.setUint16(6, 0x800, true);
    local.setUint16(12, 0x21, true);
    local.setUint32(14, sum, true);
    local.setUint32(18, body.length, true);
    local.setUint32(22, body.length, true);
    local.setUint16(26, name.length, true);
    central.setUint32(0, 0x02014b50, true);
    central.setUint16(4, 20, true);
    central.setUint16(6, 20, true);
    central.setUint16(8, 0x800, true);
    central.setUint16(14, 0x21, true);
    central.setUint32(16, sum, true);
    central.setUint32(20, body.length, true);
    central.setUint32(24, body.length, true);
    central.setUint16(28, name.length, true);
    central.setUint32(42, offset, true);
    chunks.push(new Uint8Array(local.buffer), name, body);
    directory.push(new Uint8Array(central.buffer), name);
    offset += 30 + name.length + body.length;
  }
  const centralSize = directory.reduce((n, b) => n + b.length, 0),
    end = header(22),
    count = Object.keys(files).length;
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, count, true);
  end.setUint16(10, count, true);
  end.setUint32(12, centralSize, true);
  end.setUint32(16, offset, true);
  const all = [...chunks, ...directory, new Uint8Array(end.buffer)],
    output = new Uint8Array(offset + centralSize + 22);
  let position = 0;
  for (const bytes of all) {
    output.set(bytes, position);
    position += bytes.length;
  }
  return output;
}
